function _nb_token(nb::Neighborhood)::String
    nb == NB_INCLUSION && return "INC"
    nb == NB_EXCLUSION && return "EXC"
    return "SYM_DIFF"
end

function _u_token(U::Uncertainty)::String
    U == U_NOMINAL && return "NOMINAL"
    U == U_INTERVAL && return "INTERVAL"
    U == U_CONT_BUDGET && return "CONT"
    return "DISC"
end

function _status_token(st::Status)::String
    st == ST_OK && return "OK"
    st == ST_INFEASIBLE && return "INFEASIBLE"
    st == ST_TIME_LIMIT && return "TIME_LIMIT"
    st == ST_UNBOUNDED && return "UNBOUNDED"
    st == ST_NOT_IMPL && return "NOT_IMPL"
    return "ERROR"
end

function _method_token(m::Method)::String
    m == METHOD_COMB && return "COMB"
    m == METHOD_MIP && return "MIP"
    return "AUTO"
end

function _problem_token(problem::Symbol)::String
    return String(problem)
end

"""
    sample_scenario(net, params, rng) -> Vector{Float64}

One second-stage cost vector drawn from `params.uncertainty`, independent of
any solver. Discrete budget: at most ``Δ`` uniformly chosen arcs jump to
``\\hat{c}+d``. Continuous budget: a random permutation dumps ``Γ`` onto
arcs up to each ``d_a``. Interval: each arc independently uniform in
``[\\hat{c}_a, \\hat{c}_a+d_a]``. Nominal: ``\\hat{c}``.
"""
function sample_scenario(
    net::Network,
    params::Params,
    rng::AbstractRNG,
)::Vector{Float64}
    m = Int(net.graph.m)
    c_hat = net.costs.c_hat
    d = net.costs.d
    w = Vector{Float64}(undef, m)
    U = params.uncertainty
    if U == U_NOMINAL
        @inbounds for a in 1:m
            w[a] = c_hat[a]
        end
        return w
    elseif U == U_INTERVAL
        @inbounds for a in 1:m
            w[a] = c_hat[a] + d[a] * rand(rng)
        end
        return w
    elseif U == U_DISC_BUDGET
        delta = _require_delta(params.delta)
        @inbounds for a in 1:m
            w[a] = c_hat[a]
        end
        k = delta < m ? delta : m
        if k > 0 && m > 0
            for a in randperm(rng, m)[1:k]
                w[a] = c_hat[a] + d[a]
            end
        end
        return w
    end
    gamma = _require_gamma(params.gamma)
    rem = gamma
    @inbounds for a in 1:m
        w[a] = c_hat[a]
    end
    if m == 0 || rem <= 0.0
        return w
    end
    for a in randperm(rng, m)
        rem <= 0.0 && break
        take = d[a] < rem ? d[a] : rem
        w[a] += take
        rem -= take
    end
    return w
end

function _solve_experiment(
    net::Network,
    params::Params,
    solver::Solver,
    problem::Symbol,
)::Solution
    if problem === :nom
        return solve_sp(net, net.costs.c_hat, solver)
    elseif problem === :rob
        return solve_rob(
            net,
            params_rob(params.uncertainty; gamma = params.gamma, delta = params.delta),
            solver,
        )
    elseif problem === :rec
        return solve_rec(net, params, solver)
    elseif problem === :approx
        return approx_rrsp(net, params, solver)
    elseif problem === :rrsp
        return solve_rrsp(net, params, solver)
    end
    throw(ArgumentError("unknown experiment problem $problem"))
end

function _worstcase_second(
    net::Network,
    params::Params,
    solver::Solver,
    problem::Symbol,
    sol::Solution,
)::Float64
    sol.status != ST_OK && return Inf
    if problem === :rob
        return sol.z
    end
    wc = eval_worstcase(net, params, sol.first, solver)
    # Not evaluable (e.g. no optimizer): report NaN rather than another quantity.
    return isfinite(wc) ? wc : NaN
end

