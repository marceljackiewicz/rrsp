"""
    experiment_eval(net, params, solver; problem, n_samples, rng, ...) -> NamedTuple

Run one nested model (`:nom`, `:rob`, `:rec`, `:rrsp`, or `:approx`) and
return a CSV row: objective `z`, nominal cost `z_nom` of the committed path,
worst-case second-stage `z_wc`, optional mean recovered / unrecovered sample
costs, time, MIP size / nodes, and (when `bounds=true`) theoretical
approximation factors.

Sampled scenarios are generated by [`sample_scenario`](@ref) and evaluated
with [`eval_recovered`](@ref) on the committed first-stage path.
"""
function experiment_eval(
    net::Network,
    params::Params,
    solver::Solver;
    problem::Symbol = :rrsp,
    n_samples::Integer = 0,
    rng::AbstractRNG = Random.default_rng(),
    family::AbstractString = "",
    cost_model::AbstractString = "",
    c_mode::AbstractString = "",
    formulation::AbstractString = "",
    seed::Integer = 0,
    bounds::Bool = false,
)
    sol = _solve_experiment(net, params, solver, problem)
    ok = sol.status == ST_OK
    z_nom = ok ? eval_nominal(net, sol.first) : Inf
    z_first = ok ? sol.z_first : Inf
    z_wc = _worstcase_second(net, params, solver, problem, sol)
    ns = Int(n_samples)
    z_sampled = NaN
    z_sampled_x = NaN
    if ok && ns > 0
        acc_r = 0.0
        acc_x = 0.0
        n_ok = 0
        for _ in 1:ns
            w = sample_scenario(net, params, rng)
            zr = eval_recovered(net, params, sol.first, w, solver)
            isfinite(zr) || continue
            acc_r += zr
            acc_x += path_cost(sol.first, w)
            n_ok += 1
        end
        if n_ok > 0
            z_sampled = acc_r / n_ok
            z_sampled_x = acc_x / n_ok
        end
    end
    fac = bounds ? approx_bound_factors(net, params, solver) :
        approx_bound_factors(net, params, nothing)
    meth = sol.method_used
    return (
        family = String(family),
        n = Int(net.graph.n),
        m = Int(net.graph.m),
        problem = _problem_token(problem),
        uncertainty = _u_token(params.uncertainty),
        neighborhood = _nb_token(params.neighborhood),
        k = Int(params.k),
        gamma = params.gamma,
        delta = Int(params.delta),
        c_mode = String(c_mode),
        cost_model = String(cost_model),
        formulation = String(formulation),
        seed = Int(seed),
        method = _method_token(meth),
        status = _status_token(sol.status),
        z = ok ? sol.z : Inf,
        z_nom = z_nom,
        z_first = z_first,
        z_wc = z_wc,
        z_sampled = z_sampled,
        z_sampled_x = z_sampled_x,
        n_samples = ns,
        time_sec = sol.time_sec,
        mip_gap = sol.mip_gap,
        mip_nodes = Int(sol.mip_nodes),
        n_binaries = Int(sol.n_binaries),
        n_constraints = Int(sol.n_constraints),
        alpha = fac.alpha,
        kappa = fac.kappa,
        nu = fac.nu,
        bound_alpha = fac.bound_alpha,
        bound_kappa = fac.bound_kappa,
        bound_nu = fac.bound_nu,
        bound_m = fac.bound_m,
        bound = fac.bound,
    )
end

function _csv_cell(x)::String
    if x isa AbstractString
        if occursin(r"[,\"\n]", x)
            return "\"" * replace(x, "\"" => "\"\"") * "\""
        end
        return String(x)
    elseif x isa Float64
        isnan(x) && return "NaN"
        isinf(x) && return x > 0 ? "Inf" : "-Inf"
        return string(x)
    end
    return string(x)
end

"""
    experiment_csv_header() -> String

Header line for [`write_experiment_csv`](@ref).
"""
function experiment_csv_header()::String
    return join(String.(EXPERIMENT_COLUMNS), ",")
end

function _csv_line(row, columns)::String
    parts = Vector{String}(undef, length(columns))
    @inbounds for i in 1:length(columns)
        parts[i] = _csv_cell(getfield(row, columns[i]))
    end
    return join(parts, ",")
end

function experiment_csv_line(row)::String
    return _csv_line(row, EXPERIMENT_COLUMNS)
end

function _write_named_csv(path::AbstractString, rows, columns; append::Bool = false)::Nothing
    dir = dirname(path)
    if !isempty(dir) && !isdir(dir)
        mkpath(dir)
    end
    write_header = !append || !isfile(path) || filesize(path) == 0
    open(path, append ? "a" : "w") do io
        write_header && println(io, join(String.(columns), ","))
        for row in rows
            println(io, _csv_line(row, columns))
        end
    end
    return nothing
end

"""
    write_experiment_csv(path, rows; append=false)

Write named-tuple experiment rows as CSV. Creates parent directories.
"""
function write_experiment_csv(
    path::AbstractString,
    rows;
    append::Bool = false,
)::Nothing
    return _write_named_csv(path, rows, EXPERIMENT_COLUMNS; append = append)
end

"""
    experiment_sanity(net, solver) -> Vector{String}

Sanity checks from the implementation plan: with ``C = 0`` and ``k = 0``,
RRSP matches ROB on each uncertainty set; RRSP is nonincreasing in ``k``
under interval uncertainty; graphs in which every ``s``–``t`` path has the same number of arcs satisfy the
neighborhood identity. Returns the list of failing messages (empty if all hold).
"""
function experiment_sanity(net::Network, solver::Solver)::Vector{String}
    fails = String[]
    g = net.graph
    m = Int(g.m)
    c0 = costs_new(zeros(Float64, m), net.costs.c_hat, net.costs.d)
    net0 = network_new(g, net.s, net.t, c0)
    combos = (
        (U_INTERVAL, 0.0, 0),
        (U_CONT_BUDGET, 5.0, 0),
        (U_DISC_BUDGET, 0.0, 1),
    )
    for (U, gamma, delta) in combos
        rob = solve_rob(net0, params_rob(U; gamma = gamma, delta = delta), solver)
        rrsp = solve_rrsp(
            net0,
            params_rrsp(U, NB_INCLUSION, 0; gamma = gamma, delta = delta),
            solver,
        )
        if rob.status == ST_OK && rrsp.status == ST_OK
            if abs(rob.z - rrsp.z) > 1e-8
                push!(fails, "k=0 C=0: RRSP z=$(rrsp.z) != ROB z=$(rob.z) for $U")
            end
        elseif rob.status != rrsp.status
            push!(fails, "k=0 C=0: status ROB=$(rob.status) RRSP=$(rrsp.status) for $U")
        end
    end
    # Monotonicity in k is vacuous for C = 0 (Rec is then constant), so use C = ĉ.
    netc = all(==(0.0), net.costs.C) ?
        network_new(g, net.s, net.t, costs_new(net.costs.c_hat, net.costs.c_hat, net.costs.d)) : net
    prev = Inf
    for k in 0:3
        sol = solve_rec(netc, params_rrsp(U_INTERVAL, NB_INCLUSION, k), solver)
        if sol.status == ST_OK
            if sol.z > prev + 1e-8
                push!(fails, "Rec z increased at k=$k")
            end
            prev = sol.z
        end
    end
    if is_st_layered(g, net.s, net.t)
        params_i = params_rrsp(U_INTERVAL, NB_INCLUSION, 1)
        params_e = params_rrsp(U_INTERVAL, NB_EXCLUSION, 1)
        params_s = params_rrsp(U_INTERVAL, NB_SYMDIFF, 2)
        zi = solve_rec(net0, params_i, solver)
        ze = solve_rec(net0, params_e, solver)
        zs = solve_rec(net0, params_s, solver)
        if zi.status == ST_OK && ze.status == ST_OK && zs.status == ST_OK
            if abs(zi.z - ze.z) > 1e-8 || abs(ze.z - zs.z) > 1e-8
                push!(fails, "layered neighborhood identity failed")
            end
        end
    end
    return fails
end
